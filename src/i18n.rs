use serde::Deserialize;

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Language {
    Ru,
    Zh,
    En,
}

impl Language {
    pub fn from_str_code(code: &str) -> Self {
        match code.to_lowercase().as_str() {
            "ru" => Language::Ru,
            "zh" => Language::Zh,
            _ => Language::En,
        }
    }

    pub fn to_str_code(self) -> &'static str {
        match self {
            Language::Ru => "ru",
            Language::Zh => "zh",
            Language::En => "en",
        }
    }

    pub fn to_code(self) -> &'static str {
        self.to_str_code()
    }

    pub fn from_index(index: i32) -> Self {
        match index {
            1 => Language::Ru,
            2 => Language::Zh,
            _ => Language::En,
        }
    }

    pub fn to_index(self) -> i32 {
        match self {
            Language::En => 0,
            Language::Ru => 1,
            Language::Zh => 2,
        }
    }
}

